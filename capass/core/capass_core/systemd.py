# その他のモジュールやROOTPATHのディレクトリ起点の相対パスでのimport
from pathlib import Path
from capass_core.paths import AppPaths

UNIT_MARKER = "# Generated by capass init"


def render_unit(paths: AppPaths, user: str, group: str, log_dir: Path, data_dir: Path, description: str, exec_args: str) -> str:
    """systemdのサービスファイル(/etc/systemd/system/capass.service)。常駐プロセス(capass <exec_args>)を、実行ユーザで常駐させる。
    待ち受けのポート番号は、設定ファイル(confs/capass.conf)から読む。"""
    return f"""{UNIT_MARKER}
[Unit]
Description={description}
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User={user}
Group={group}
WorkingDirectory={paths.root}
ExecStart={paths.wrapper} {exec_args}
Restart=on-failure
RestartSec=5

# 権限の制限(常駐プロセスが乗っ取られたときの、被害を小さくする)
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths={log_dir} {data_dir}

[Install]
WantedBy=multi-user.target
"""
